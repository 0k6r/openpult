#!/usr/bin/env python3
"""Reference encoder for protocol v2 signal blobs; regenerates testdata/ir_vectors.json.

Usage: python3 tools/gen_ir_vectors.py [--check]
The table is built in order of first appearance (intro, then repeat), as the app does.
"""
import base64
import json
import math
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "testdata" / "ir_vectors.json"


def leb128(value):
    out = bytearray()
    while True:
        byte = value & 0x7F
        value >>= 7
        if value:
            out.append(byte | 0x80)
        else:
            out.append(byte)
            return bytes(out)


def nibbles(symbols):
    out = bytearray()
    for i in range(0, len(symbols), 2):
        hi = symbols[i]
        lo = symbols[i + 1] if i + 1 < len(symbols) else 0
        out.append(hi << 4 | lo)
    return bytes(out)


def blob(carrier_hz, duty_pct, min_repeats, intro, repeat):
    assert len(intro) % 2 == 0 and len(repeat) % 2 == 0
    table = []
    for d in intro + repeat:
        if d not in table:
            table.append(d)
    assert 1 <= len(table) <= 16
    index = {d: i for i, d in enumerate(table)}
    out = bytearray()
    out += carrier_hz.to_bytes(2, "little")
    out += bytes([duty_pct, min_repeats, len(table)])
    out += len(intro).to_bytes(2, "little") + len(repeat).to_bytes(2, "little")
    for d in table:
        out += leb128(d)
    out += nibbles([index[d] for d in intro])
    out += nibbles([index[d] for d in repeat])
    return table, bytes(out)


def play_writes(sig_id, data, max_write):
    chunk = max_write - 4
    parts = [data[i:i + chunk] for i in range(0, len(data), chunk)] or [b""]
    writes = []
    for n, part in enumerate(parts):
        frag = n | (0x80 if n == len(parts) - 1 else 0)
        writes.append(bytes([0x10, 0x00, sig_id, frag]) + part)
    return writes


def with_gap(frame, period_us):
    """frame ends with a mark; append the space that completes the fixed period."""
    assert len(frame) % 2 == 1
    return frame + [period_us - sum(frame)]


def sirc_frame(bits, device, command):
    seq = [(command >> i) & 1 for i in range(7)] + [(device >> i) & 1 for i in range(bits - 7)]
    frame = [2400]
    for b in seq:
        frame += [600, 1200 if b else 600]
    return with_gap(frame, 45000)


def nec_frame(address, command):
    data = [address, address ^ 0xFF, command, command ^ 0xFF]
    frame = [9000, 4500]
    for byte in data:
        for i in range(8):
            frame += [562, 1687 if (byte >> i) & 1 else 562]
    frame += [562]
    return with_gap(frame, 108000)


def nec_repeat():
    return with_gap([9000, 2250, 562], 108000)


def limits_intro():
    """16 distinct durations from 1 to 500000 us (1-3 byte varints), 30 ms marks, exactly 1 s."""
    intro = [1, 2, 127, 128, 16383, 16384, 30000, 300, 250, 1000, 500, 2000, 600, 4000, 30000, 500000]
    intro += [30000, 16384] * 7 + [30000, 43637]
    assert len(set(intro)) == 16 and sum(intro) == 1_000_000 and max(intro[0::2]) == 30000
    return intro


SIRC = [
    ("Power", "AAAAAQAAAAEAAAAVAw==", 0xA90),
    ("WakeUp", "AAAAAQAAAAEAAAAuAw==", 0x750),
    ("PowerOff", "AAAAAQAAAAEAAAAvAw==", 0xF50),
    ("Num1", "AAAAAQAAAAEAAAAAAw==", 0x010),
    ("VolumeUp", "AAAAAQAAAAEAAAASAw==", 0x490),
    ("Back", "AAAAAgAAAJcAAAAjAw==", 0x62E9),
    ("Options", "AAAAAgAAAJcAAAA2Aw==", 0x36E9),
    ("Hdmi1", "AAAAAgAAABoAAABaAw==", 0x2D58),
]


def sirc_entry(name, ircc, value):
    raw = base64.b64decode(ircc)
    kind, device, command = (int.from_bytes(raw[i:i + 4], "big") for i in (0, 4, 8))
    bits = {1: 12, 2: 15, 3: 20}[kind]
    seq = [(command >> i) & 1 for i in range(7)] + [(device >> i) & 1 for i in range(bits - 7)]
    computed = 0
    for b in seq:
        computed = computed << 1 | b
    assert computed == value, (name, hex(computed))
    return {"key": name, "ircc": ircc, "bits": bits, "device": device, "command": command,
            "value": f"0x{value:X}"}


def signal_entry(name, carrier, duty, min_repeats, intro, repeat, note):
    table, data = blob(carrier, duty, min_repeats, intro, repeat)
    return {
        "name": name,
        "note": note,
        "carrier_hz": carrier,
        "duty_pct": duty,
        "min_repeats": min_repeats,
        "intro": intro,
        "repeat": repeat,
        "table": table,
        "blob_hex": data.hex(),
        "play_hex": [w.hex() for w in play_writes(1, data, 244)],
        "play_hex_mtu23": [w.hex() for w in play_writes(1, data, 20)],
    }


def build():
    sony_power = sirc_frame(12, 1, 21)
    vectors = {
        "schema": 1,
        "comment": "Generated by tools/gen_ir_vectors.py — do not edit by hand. See firmware/PROTOCOL.md.",
        "sirc": [sirc_entry(*s) for s in SIRC],
        "signals": [
            signal_entry("sony-power-sirc12", 40000, 33, 3, [], sony_power,
                         "Sony Power (12-bit SIRC dev 1 cmd 21), repeat only, 45 ms period"),
            signal_entry("nec-lg-power", 38000, 33, 1, nec_frame(0x04, 0x08), nec_repeat(),
                         "NEC addr 0x04 cmd 0x08 (LG Power, 0x20DF10EF), frame + repeat code, 108 ms period"),
            signal_entry("raw-limits", 65535, 50, 20, limits_intro(), [],
                         "intro only, 16 table entries, 1-3 byte varints, 30 ms mark, 1 s section"),
        ],
        "hold": {
            "formula": "count = clamp(ceil(180 ms / repeat unit) + 1, 2, 20)",
            "examples": [{"repeat_unit_us": 45000, "count": 5}, {"repeat_unit_us": 108000, "count": 3}],
        },
    }
    for ex in vectors["hold"]["examples"]:
        assert min(max(math.ceil(180000 / ex["repeat_unit_us"]) + 1, 2), 20) == ex["count"]
    return vectors


def main():
    vectors = build()
    sony = vectors["signals"][0]
    expected = ("100001 80".replace(" ", "") + "409c21030400001a00" + "e012d804b009c8c901"
                + "01211121112111112111111113")
    assert sony["play_hex"] == [expected], sony["play_hex"]
    text = json.dumps(vectors, indent=2) + "\n"
    if "--check" in sys.argv:
        if OUT.read_text() != text:
            sys.exit("testdata/ir_vectors.json is stale: run tools/gen_ir_vectors.py")
        return
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
